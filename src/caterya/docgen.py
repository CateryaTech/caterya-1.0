"""Generate METRICS.md, PARAMETERS.md and JSON Schemas from the code (so docs cannot drift from reality)."""
from __future__ import annotations

import json
import os
from typing import Any, Dict

from .assurance.profiles import PROFILES
from .metrics import registry as mreg
from .regulatory.mapping import DISCLAIMER, FRAMEWORKS
from .version import SPEC_VERSION, __version__

_S = "https://json-schema.org/draft/2020-12/schema"


def schemas() -> Dict[str, Dict[str, Any]]:
    sig = {"type": "object", "required": ["alg", "key_id", "sig"], "properties": {"alg": {"type": "string"}, "key_id": {"type": "string"}, "sig": {"type": "string"}}}
    ev = {"$schema": _S, "$id": "https://caterya.tech/schemas/evidence.v1.json", "title": "CATERYA Evidence", "type": "object",
          "required": ["kind", "claim", "timestamp", "prev_hash", "record_hash", "evidence_id", "signature", "spec"],
          "properties": {"kind": {"enum": ["metric", "car", "decision", "guardrail", "swarm", "monitor", "incident", "mapping", "note"]},
                         "claim": {"type": "string"}, "metric_id": {"type": "string"}, "spec_hash": {"type": "string"}, "system_hash": {"type": "string"},
                         "dataset_hash": {"type": "string"}, "seed": {"type": ["integer", "null"]}, "result": {"type": "object"},
                         "ci": {"type": ["array", "null"], "items": {"type": "number"}, "minItems": 2, "maxItems": 2},
                         "limitations": {"type": "array", "items": {"type": "string"}}, "untested": {"type": "array", "items": {"type": "string"}},
                         "actor": {"type": "string"}, "timestamp": {"type": "string", "format": "date-time"}, "prev_hash": {"type": "string"},
                         "record_hash": {"type": "string"}, "evidence_id": {"type": "string", "pattern": "^ev_[0-9a-f]{16}$"}, "spec": {"const": SPEC_VERSION},
                         "signature": sig}}
    trace = {"$schema": _S, "$id": "https://caterya.tech/schemas/trace.v1.json", "title": "CATERYA agent trace", "type": "object", "required": ["task_id", "steps"],
             "properties": {"task_id": {"type": "string"}, "goal": {"type": "string"}, "policy": {"type": "object"},
                            "steps": {"type": "array", "items": {"type": "object", "required": ["type"], "properties": {
                                "type": {"enum": ["tool_call", "message", "escalate"]}, "tool": {"type": "string"}, "ok": {"type": "boolean"}, "cost": {"type": "number"},
                                "write": {"type": "boolean"}, "scope": {"type": "string"}, "risk": {"type": "string"},
                                "requires_approval": {"type": "boolean"}, "approved_by": {"type": "string"}}}},
                            "outcome": {"type": "object", "properties": {"success": {"type": "boolean"}}},
                            "injection_followed": {"type": ["boolean", "null"]}}}
    bundle = {"$schema": _S, "$id": "https://caterya.tech/schemas/bundle.v1.json", "title": "CATERYA evidence bundle", "type": "object",
              "required": ["version", "keyring", "evidence", "tree_head"], "properties": {"version": {"const": "caterya.bundle/v1"}, "keyring": {"type": "object"},
                                                                                         "evidence": {"type": "array", "items": {"$ref": "evidence.v1.json"}},
                                                                                         "tree_head": {"type": "object"}, "anchors": {"type": "array"}}}
    return {"evidence.v1.json": ev, "trace.v1.json": trace, "bundle.v1.json": bundle}


def metrics_md() -> str:
    mreg.load_all()
    L = [f"# Metric catalogue (generated by `caterya docs`, v{__version__})", "",
         f"{len(mreg.REGISTRY)} registered metrics. A changed definition changes the metric's `spec_hash`, which every Evidence binds to.", ""]
    for dom, ids in sorted(mreg.by_domain().items()):
        L += [f"## {dom}", "", "| id | maturity | cost | requires | default parameters |", "|---|---|---|---|---|"]
        for i in sorted(ids):
            m = mreg.REGISTRY[i]
            L.append(f"| `{m.id}` | {m.maturity} | {m.cost} | {', '.join(m.requires) or '-'} | `{json.dumps(m.defaults, sort_keys=True)}` |")
        L.append("")
        for i in sorted(ids):
            m = mreg.REGISTRY[i]
            L += [f"### `{m.id}`", m.description, ""]
            if m.assumptions:
                L += ["*Assumptions:* " + "; ".join(m.assumptions)]
            if m.limitations:
                L += ["*Limitations:* " + "; ".join(m.limitations)]
            L.append("")
    return "\n".join(L)


def parameters_md() -> str:
    L = ["# Profiles and thresholds (generated)", "", "**Thresholds are illustrative defaults, not standards.** Set and justify your own "
         "(docs/VALIDATION_PROTOCOL.md). `INFO` metrics never affect verdicts, risk, coverage or the recommendation.", ""]
    for p in PROFILES.values():
        L += [f"## {p.name}", p.description, "", f"min_coverage = {p.min_coverage}, default impact = {p.impact_default}", "",
              "| metric | threshold | weight | required | info-only |", "|---|---|---|---|---|"]
        for k, v in p.metrics.items():
            L.append(f"| `{k}` | {v.threshold} | {v.weight} | {'yes' if v.required else ''} | {'yes' if v.informational else ''} |")
        L.append("")
    return "\n".join(L)


def regulatory_md() -> str:
    L = ["# Regulatory theme mapping (generated)", "", f"> {DISCLAIMER}", ""]
    for f, d in FRAMEWORKS.items():
        L += [f"## {f}  (status: {d['status']})"]
        if d.get("note"):
            L.append(f"*{d['note']}*")
        L += ["", "| theme | mapped metrics |", "|---|---|"]
        L += [f"| {t} | {', '.join('`'+m+'`' for m in ms)} |" for t, ms in d["themes"].items()]
        L.append("")
    return "\n".join(L)


def generate(root: str) -> None:
    os.makedirs(os.path.join(root, "docs"), exist_ok=True)
    os.makedirs(os.path.join(root, "schemas"), exist_ok=True)
    for name, text in (("METRICS.md", metrics_md()), ("PARAMETERS.md", parameters_md()), ("REGULATORY.md", regulatory_md())):
        with open(os.path.join(root, "docs", name), "w", encoding="utf-8") as fh:
            fh.write(text + "\n")
    for name, sch in schemas().items():
        with open(os.path.join(root, "schemas", name), "w", encoding="utf-8") as fh:
            json.dump(sch, fh, indent=2, sort_keys=True)
            fh.write("\n")
